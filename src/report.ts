import type { CheckReport, CheckResult, Verdict } from "./types.js";

const VERDICT_ICON: Record<Verdict, string> = {
  pass: "✅",
  warn: "⚠️",
  fail: "❌",
  skip: "–",
};

const VERDICT_LABEL: Record<Verdict, string> = {
  pass: "pass",
  warn: "warn",
  fail: "fail",
  skip: "skip",
};

const SEVERITY_ICON = { error: "🔴", warning: "🟠", info: "🔵" } as const;

const STATUS_LABEL: Record<string, string> = {
  compatible: "✅ compatible",
  partial: "⚠️ partial",
  legacy: "❌ legacy (pre-2026-07-28)",
  unreachable: "❌ unreachable",
  "not-probed": "– not probed",
};

function statusBadge(report: CheckReport): string {
  if (!report.probe) return "";
  const status = report.probe.status;
  const color = status === "compatible" ? "brightgreen" : status === "partial" ? "yellow" : "red";
  const label = encodeURIComponent(`MCP ${report.specVersion}`);
  const message = encodeURIComponent(status === "legacy" ? "legacy" : status);
  return `![MCP ${report.specVersion}: ${status}](https://img.shields.io/badge/${label}-${message}-${color})`;
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

function formatDuration(ms: number): string {
  if (ms < 1_000) return `${ms}ms`;
  return `${(ms / 1_000).toFixed(1)}s`;
}

function describeCheck(check: CheckResult): string {
  return `[${check.requirement}] ${check.title}`;
}

export function renderText(report: CheckReport): string {
  const lines: string[] = [];
  lines.push(`mcp-dual ${report.tool.version} — MCP ${report.specVersion} report`);
  lines.push(`Generated: ${report.generatedAt}`);
  lines.push("");

  if (report.probe) {
    const probe = report.probe;
    lines.push(`Target: ${probe.target} (${probe.transport})`);
    lines.push(
      `Status: ${STATUS_LABEL[probe.status] ?? probe.status} · ${probe.summary.pass} pass, ${probe.summary.warn} warn, ${probe.summary.fail} fail, ${probe.summary.skip} skip · ${formatDuration(probe.durationMs)}`,
    );
    lines.push("");
    for (const check of probe.checks) {
      lines.push(`  ${VERDICT_ICON[check.verdict]} ${describeCheck(check)}`);
      lines.push(`     ${check.detail}`);
    }
    lines.push("");
  }

  if (report.static) {
    const scan = report.static;
    lines.push(`Static scan: ${scan.filesScanned} files · ${scan.counts.error} error, ${scan.counts.warning} warning, ${scan.counts.info} info`);
    for (const finding of scan.findings.slice(0, 60)) {
      lines.push(`  ${SEVERITY_ICON[finding.severity]} ${finding.ruleId} ${finding.file}:${finding.line}`);
      lines.push(`     ${finding.message}${finding.occurrences > 1 ? ` (${finding.occurrences} occurrences)` : ""}`);
      lines.push(`     → ${finding.suggestion}`);
    }
    if (scan.findings.length > 60) lines.push(`  … ${scan.findings.length - 60} more findings (use --format json for all)`);
    lines.push("");
  }

  if (report.nextSteps.length > 0) {
    lines.push("Next steps:");
    report.nextSteps.forEach((step, index) => lines.push(`  ${index + 1}. ${step}`));
    lines.push("");
  }
  lines.push(`Exit code: ${report.exitCode} (0 compatible, 1 incompatible, 2 unreachable/usage)`);
  return lines.join("\n");
}

export function renderMarkdown(report: CheckReport): string {
  const lines: string[] = [];
  lines.push(`# MCP ${report.specVersion} compatibility report`);
  lines.push("");
  const badge = statusBadge(report);
  if (badge) lines.push(badge, "");
  lines.push(`Generated by \`mcp-dual ${report.tool.version}\` at ${report.generatedAt}.`);
  lines.push("");

  if (report.probe) {
    const probe = report.probe;
    lines.push(`**Target:** \`${probe.target}\` (${probe.transport})`);
    lines.push("");
    lines.push(`**Status:** ${STATUS_LABEL[probe.status] ?? probe.status} — ${probe.summary.pass} pass · ${probe.summary.warn} warn · ${probe.summary.fail} fail · ${probe.summary.skip} skip (${formatDuration(probe.durationMs)})`);
    lines.push("");
    lines.push("| Check | Requirement | Result | Detail |");
    lines.push("| --- | --- | --- | --- |");
    for (const check of probe.checks) {
      lines.push(
        `| ${escapeCell(check.title)} | ${check.requirement} | ${VERDICT_ICON[check.verdict]} ${VERDICT_LABEL[check.verdict]} | ${escapeCell(check.detail)} |`,
      );
    }
    lines.push("");
  }

  if (report.static) {
    const scan = report.static;
    lines.push("## Static findings");
    lines.push("");
    lines.push(
      `${scan.filesScanned} files scanned · **${scan.counts.error}** error · **${scan.counts.warning}** warning · **${scan.counts.info}** info`,
    );
    lines.push("");
    if (scan.findings.length > 0) {
      lines.push("| Severity | Rule | Location | Finding | Fix |");
      lines.push("| --- | --- | --- | --- | --- |");
      for (const finding of scan.findings.slice(0, 100)) {
        lines.push(
          `| ${SEVERITY_ICON[finding.severity]} ${finding.severity} | \`${finding.ruleId}\` | \`${finding.file}:${finding.line}\` | ${escapeCell(finding.message)} | ${escapeCell(finding.suggestion)} |`,
        );
      }
      if (scan.findings.length > 100) lines.push(`| … | | | ${scan.findings.length - 100} more findings in JSON output | |`);
    } else {
      lines.push("No legacy patterns found.");
    }
    lines.push("");
  }

  if (report.nextSteps.length > 0) {
    lines.push("## Next steps");
    lines.push("");
    for (const step of report.nextSteps) lines.push(`1. ${step}`);
    lines.push("");
  }

  lines.push("---");
  lines.push("");
  lines.push("Exit code: `0` compatible · `1` incompatible/partial · `2` unreachable/usage.");
  return lines.join("\n");
}

export function renderJson(report: CheckReport): string {
  return JSON.stringify(report, null, 2);
}
